import assert from 'node:assert/strict';
import { createSurfaceMovement } from '../src/app/surface-movement.js';
import { PLAYER_SPEED } from '../src/core/runtime-config.js';
import { ITEMS } from '../src/content/rpg-data.js';
const player={x:10,y:10,dir:0,boost:0}, state={keys:new Set(),touch:{},sprint:false,footstepAt:0};
const world={cat:{x:8,y:8,facing:0},boxCollides:()=>false};
const rpg={speedMult:()=>1,mountSpeedMult:()=>1,activePet:()=>({kind:'cat'})};
const controller=createSurfaceMovement({player,state,world,rpg,audio:{footstep(){},hover(){}},toast(){},interactTarget(){}});
controller.walkStep(1,1,.05);
assert.equal(player.dir,5);
assert.ok(Math.abs(Math.hypot(player.x-10,player.y-10)-PLAYER_SPEED*.05)<1e-9);
const start={...player};world.boxCollides=(x)=>x>start.x;
controller.walkStep(1,1,.05);
assert.equal(player.x,start.x);assert.ok(player.y>start.y);assert.equal(player.dir,0);
world.boxCollides=()=>true;
controller.walkStep(-1,0,.05);assert.equal(player.moving,false);assert.equal(player.dir,0);
world.boxCollides=()=>false;
controller.updateCat(.05);assert.ok(world.cat.moving);assert.equal(world.cat.facing,5);
state.path=[{x:20,y:20}];state.pending={kind:'item'};controller.clearPath();
assert.equal(state.path,null);assert.equal(state.pending,null);assert.equal(player.pathGoal,null);
assert.equal(ITEMS['amostra-quimica'].continent,'chem');assert.equal(ITEMS.amostra.continent,'math');
console.log('ok controlador: velocidade, deslizamento, bloqueio, pet e IDs de amostras independentes');
