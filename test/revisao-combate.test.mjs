import assert from 'node:assert/strict';
const store = new Map();
globalThis.localStorage = { getItem: k => store.get(k) ?? null, setItem: (k,v) => store.set(k,String(v)) };
const { RPG } = await import('../src/gameplay/rpg.js');
const { GROUNDS } = await import('../src/content/rpg-data.js');
const { MANA_MS } = await import('../src/content/pets.js');
const originalNow = Date.now;
let clock = 1000000000;
Date.now = () => clock;
try {
  const rpg = new RPG();
  rpg.data.mana = 3;
  rpg.data.manaAt = 0;
  rpg.pulse();
  clock += MANA_MS;
  rpg.pulse();
  assert.equal(rpg.mana(), 4, 'save sem origem de mana volta a regenerar');
  rpg.data.manaAt = clock + MANA_MS * 10;
  rpg.pulse();
  clock += MANA_MS;
  rpg.pulse();
  assert.equal(rpg.mana(), 5, 'ajuste do relógio não paralisa regeneração');
  rpg.data.mana = rpg.manaMax();
  clock += MANA_MS * 100;
  rpg.pulse();
  rpg.addMana(-3);
  rpg.pulse();
  assert.equal(rpg.mana(), rpg.manaMax() - 3, 'tempo com mana cheia não vira reserva invisível');
  const ground = GROUNDS.find(g => g.id === 'cs');
  ground.dungeon = true;
  rpg.data.levers[ground.id] = true;
  rpg.startDuel({id:'boss-rune',name:'Chefe',kind:'boss',tier:3}, ground, true);
  const d = rpg.duel;
  const c = rpg.combate;
  const ini = c.inimigos[0];
  d.habilidade = null;
  ini.hpMax = 10;
  ini.hp = 8;
  ini.x = c.jogador.x + 20;
  ini.y = c.jogador.y;
  rpg.data.spells = { 'runa-trovao': true };
  rpg.data.mana = rpg.manaMax();
  for (let i = 0; i < 3; i++) {
    c.magias.clear();
    rpg.data.mana = rpg.manaMax();
    assert.equal(c.usarMagia('runa-trovao').ok, true, `trovão ${i + 1} não saiu`);
    if (i === 0) assert.equal(d.bossPhase, 2, 'runa também provoca fase 2');
  }
  assert.equal(d.bossPhase, 3, 'runa também provoca fase 3');
} finally { Date.now = originalNow; }
