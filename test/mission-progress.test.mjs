import assert from 'node:assert/strict';
const store=new Map();
globalThis.localStorage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,String(v))};
const {RPG}=await import('../src/gameplay/rpg.js');
const {Quests,QUESTS}=await import('../src/gameplay/quests.js');
const rpg=new RPG();
const make=()=>new Quests({getBosses:()=>rpg.data.bosses});
let q=make();
const quest=QUESTS.find(q=>q.id==='chefe-math-algebra');
// o chefe é o segundo capítulo do arco: a trilha da área precisa fechar antes
q.data.done['trilha-math-algebra']=Date.now(); q.save();
assert.equal(q.accept(quest.id), true, 'com a trilha fechada, o chefe é aceitável');
assert.equal(q.ready(quest),false);
rpg.data.bosses['dungeon-math-algebra']=Date.now(); rpg.save();
assert.equal(q.ready(quest),true,'chefe da caverna satisfaz a missão de área');
q=make();
assert.equal(q.ready(quest),true,'chefe continua pronto depois de recarregar');
q.accept('cacador'); q.report('hunts',3);
assert.equal(q.ready(QUESTS.find(q=>q.id==='cacador')),true,'três monstros da matilha contam como três');
q.report('hunts',-1); q.report('hunts',NaN);
assert.equal(q.data.stats.hunts,3);
rpg.noteMonster({id:'sample-monster',kind:'bat',tier:1,name:'Bit',continent:'cs',theme:'lógica'});
const saved=new RPG().seenView().find(e=>e.kind==='bat');
assert.equal(saved.continent,'cs'); assert.equal(saved.theme,'lógica');
console.log('ok missões: chefe lê RPG, matilha conta monstros e bestiário preserva o tema');
