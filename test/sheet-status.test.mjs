import assert from 'node:assert/strict';
import {makeDocument} from './ui-dom.mjs';
const {document} = makeDocument(['sheet-body']);
globalThis.document = document;
globalThis.localStorage = {getItem:()=>null,setItem(){}};
const {RPG} = await import('../src/gameplay/rpg.js');
const {createSheet} = await import('../src/ui/sheet.js');
const rpg = new RPG();
const ui = createSheet({rpg,getLevel:()=>1,getXp:()=>0,toast(){},audio:{}});
rpg.data.pets.papagaio = {bond:3}; rpg.data.petActive = 'papagaio';
ui.render();
let use = document.getElementById('sheet-body').querySelector('.company-pet').querySelectorAll('*').find(n=>n.tagName==='BUTTON');
assert.equal(use.disabled,true);
assert.match(use.textContent,/somente em combate/);
rpg.data.pets.sapo = {bond:3}; rpg.data.petActive = 'sapo';
rpg.data.petCd[rpg.activePet().ability.id] = Date.now()+10000;
ui.render();
use = document.getElementById('sheet-body').querySelector('.company-pet').querySelectorAll('*').find(n=>n.tagName==='BUTTON');
assert.equal(use.disabled,true);
use.focus();
rpg.data.petCd[rpg.activePet().ability.id] = 0;
rpg.data.mana = rpg.manaMax();
ui.refresh();
assert.equal(use.disabled,false,'fim do descanso reabilita habilidade sem reabrir ficha');
assert.equal(document.activeElement,use,'atualizar status mantém foco');
assert.equal(document.getElementById('sheet-body').querySelector('.company-pet').querySelectorAll('*').find(n=>n.tagName==='BUTTON'),use);
