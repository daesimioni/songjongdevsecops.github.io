import assert from 'node:assert/strict';
const events=new Map();
globalThis.document={getElementById:()=>null,querySelectorAll:()=>[]};
globalThis.window={addEventListener:(type,handler)=>events.set(type,handler)};
globalThis.localStorage={getItem:()=>null,setItem(){}};
const {RPG}=await import('../js/rpg.js');
const {createDungeon}=await import('../js/dungeon.js');
const {isTextEntry,nativeActivation}=await import('../js/input.js');
const rpg=new RPG();
const dg=createDungeon({rpg,audio:{chime(){},blip(){}}});
Object.assign(dg.state,{open:true,map:{W:20,H:20,grid:new Uint8Array(400).fill(1),rooms:[]},
 player:{x:10.5,y:11.5,dir:0},props:[{kind:'altar',interact:true,x:10.5,y:10.5}],sprint:false});
const event=(key,target={closest:()=>null})=>({key,target,preventDefault(){},stopImmediatePropagation(){}});
rpg.data.hp=1;
events.get('keydown')(event('f'));
assert.equal(rpg.hp(),rpg.hpMax(),'primeiro uso do altar não espera 45 segundos desde a abertura do site');
rpg.data.hp=1;
events.get('keydown')(event('f'));
assert.equal(rpg.hp(),1,'segundo uso imediato respeita recarga');
events.get('keydown')(event(' ',{closest:s=>s.includes('button')?{}:null}));
assert.equal(dg.state.sprint,false,'espaço em botão mantém ativação nativa');
dg.state.keys.add('w');dg.state.path=[{x:12,y:12}];dg.state.pending={};dg.state.sprint=true;dg.state.player.moving=true;
dg.stopControls();
assert.equal(dg.state.keys.size,0);assert.equal(dg.state.path,null);assert.equal(dg.state.pending,null);
assert.equal(dg.state.sprint,false);assert.equal(dg.state.player.moving,false);
assert.equal(isTextEntry({closest:s=>s.includes('select')?{}:null}),true);
assert.equal(isTextEntry({isContentEditable:true}),true);
assert.equal(nativeActivation(event('Enter',{closest:s=>s.includes('button')?{}:null})),true);
console.log('ok controles: foco nativo, campos editáveis, pausa completa e recarga do altar');
