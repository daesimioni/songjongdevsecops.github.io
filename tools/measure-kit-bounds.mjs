import { writeFile } from "node:fs/promises";
import { createCanvas } from "@napi-rs/canvas";
import { SPRITE_KIT } from "../src/content/sprite-kit/catalog.js";
import { paintKit } from "../src/rendering/sprite-kit/index.js";
const bounds = {};
let before = 0,
  after = 0;
for (const a of SPRITE_KIT.filter((a) => a.renderer)) {
  const b = a.bounds,
    pad = 8,
    c = createCanvas((b.w + pad * 2) * 2, (b.h + pad * 2) * 2),
    g = c.getContext("2d");
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity;
  for (const state of Object.keys(a.states || { default: [] }))
    for (const direction of a.orientations)
      for (let frame = 0; frame < a.frames; frame++) {
        g.save();
        g.scale(2, 2);
        g.translate(pad - b.x, pad - b.y);
        paintKit(g, a.id, {
          state: a.states ? state : undefined,
          direction,
          frame,
        });
        g.restore();
      }
  const data = g.getImageData(0, 0, c.width, c.height).data;
  for (let y = 0; y < c.height; y++)
    for (let x = 0; x < c.width; x++)
      if (data[(y * c.width + x) * 4 + 3]) {
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
  const left = Math.floor(minX / 2 - pad + b.x) - 2,
    top = Math.floor(minY / 2 - pad + b.y) - 2,
    right = Math.ceil((maxX + 1) / 2 - pad + b.x) + 2,
    bottom = Math.ceil((maxY + 1) / 2 - pad + b.y) + 2;
  bounds[a.id] = {
    x: left,
    y: top,
    w: right - left,
    h: bottom - top,
    padding: 2,
  };
  const poses =
    a.frames *
    a.orientations.length *
    Object.keys(a.states || { default: [] }).length;
  before += b.w * b.h * poses;
  after += (right - left) * (bottom - top) * poses;
}
await writeFile(
  "src/content/sprite-kit/measured-bounds.js",
  "// Generated by tools/measure-kit-bounds.mjs; includes every state/view/frame.\nexport const MEASURED_BOUNDS = Object.freeze(" +
    JSON.stringify(bounds, null, 2) +
    ");\nObject.values(MEASURED_BOUNDS).forEach(Object.freeze);\n",
);
console.log(
  JSON.stringify({
    entries: Object.keys(bounds).length,
    beforePixels: before,
    afterPixels: after,
    reduction: 1 - after / before,
  }),
);
